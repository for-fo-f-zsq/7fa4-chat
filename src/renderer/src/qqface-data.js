export const QUANCODE = new Map()
for (const f of QQFACES) {
  if (!QUANCODE.has(f.code.toLowerCase())) QUANCODE.set(f.code.toLowerCase(), f)
  if (f.pinyin && !QUANCODE.has(("/" + f.pinyin).toLowerCase())) QUANCODE.set(("/" + f.pinyin).toLowerCase(), f)
  for (const a of f.alias) { const k = ("/" + a).toLowerCase(); if (!QUANCODE.has(k)) QUANCODE.set(k, f) }
}

export function qqfaceUrl(file) { return "/qqface/" + file }

export const QUANCODE_PATTERN = /\/[a-zA-Z\u4e00-\u9fa5]{1,12}/g
