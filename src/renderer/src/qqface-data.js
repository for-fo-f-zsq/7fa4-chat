// 快捷码 → 表情（中文 + 全拼 + 缩写 全映射，生成期已保证无碰撞）
export const QUANCODE = new Map()
for (const f of QQFACES) {
  const codeKey = f.code.toLowerCase()
  if (!QUANCODE.has(codeKey)) QUANCODE.set(codeKey, f)
  if (f.pinyin) {
    const pyKey = ('/' + f.pinyin).toLowerCase()
    if (!QUANCODE.has(pyKey)) QUANCODE.set(pyKey, f)
  }
  for (const a of f.alias) {
    const aliasKey = ('/' + a).toLowerCase()
    if (!QUANCODE.has(aliasKey)) QUANCODE.set(aliasKey, f)
  }
}

export function qqfaceUrl(file) { return assetUrl('qqface/' + file) }

/**
 * 取表情的最短快捷码（用于点击表情时默认插入的文本）。
 * 候选：中文码 code、全拼码 "/pinyin"、以及全部 alias（"/alias"）。
 * 在全部候选中选 JS 长度最小的；长度相同时优先 alias > pinyin > code。
 * 例：/惊讶 → /jy（alias 最短）；无 alias → 比较 /pinyin 与 /中文 长度。
 */
export function qqfaceShortCode(f) {
  if (!f) return ''
  const cands = []
  if (f.code) cands.push({ s: f.code, pri: 3 })
  if (f.pinyin) cands.push({ s: '/' + f.pinyin, pri: 2 })
  for (const a of (f.alias || [])) cands.push({ s: '/' + a, pri: 1 })
  if (!cands.length) return ''
  cands.sort((x, y) => (x.s.length - y.s.length) || (x.pri - y.pri))
  return cands[0].s
}
